/**
 * 代码级维度的审计准则（纯数据，无逻辑）。
 *
 * ## 每份 rubric 是一个维度的「判据合同」
 *
 * 审计引擎把它渲染成完整的判定 prompt。字段职责固定：
 *   role       —— system prompt 的角色部分（引擎会自动接上「你没有任何工具」的纪律段）
 *   intro      —— 告诉模型它看到的是什么、从哪来的
 *   criteria   —— 每个 verdict 的定义。**verdict 词表在 registry.js，两处必须对齐**
 *   examples   —— few-shot。铁律：正反例都要给
 *   outputRule —— 对 reason / suggestion 的要求
 *
 * ## 为什么每份都必须给正例
 *
 * `check-prompts.js` 的实测教训（记在它的 buildPrompt 注释里）：只给反例会让模型把
 * 清单里所有条目一律判成有问题——而候选清单**天生全是可疑项**，这个偏置会让维度失去鉴别力。
 * 所以每份 rubric 至少一正一反，且正例要挑「看起来很像问题但其实合理」的那种。
 *
 * ## 为什么判据要写出「权威出处」
 *
 * 不是为了显得权威，而是为了**可争辩**。用户看到「这个函数该拆」时，如果理由是
 * 「《代码大全》ch7.4 的实证结论是例程超过 200 行后缺陷密度显著上升」，他可以反驳这条依据
 * 是否适用于他的场景；如果理由只是「太长了」，就只剩下服从或忽略两个选项。
 */

