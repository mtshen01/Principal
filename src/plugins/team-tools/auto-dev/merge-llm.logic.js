/**
 * 「自动合并的 LLM 兜底」纯函数层 —— 两个 prompt 与超时常量。
 *
 * 两个 prompt 解决的是**性质完全不同**的两件事，措辞不可互换：
 *   - resolveConflict：两个**已提交**分支的内容冲突。两边都是成品代码，要的是语义融合。
 *   - mergeStash：合并结果 vs 维护者**未提交、正在写**的代码。后者可能是半成品，
 *     但它是人手上活着的上下文 —— 丢了就是丢了，没有任何地方能找回来。
 *
 * 共同的硬纪律（两个 prompt 都写死）：**不许模型自己 commit / git add**。
 * 提交与索引状态由 `git.js` 统一处理，那里有「冲突标记残留就判失败」的防谎报闸；
 * 模型自行提交会绕过它，让「其实没解干净」看起来像成功。
 */

/** 单次兜底超时（对齐 revert.logic.js#REVERT_TIMEOUT_MS / side-review.js#SIDE_TIMEOUT_MS） */
export const MERGE_LLM_TIMEOUT_MS = 5 * 60_000;

/** 冲突文件清单渲染：控量避免 prompt 撑爆（记忆库一期的教训），多余的让模型自己 git status 查 */
function fileList(files) {
  const list = (files || []).filter(Boolean);
  if (!list.length) return '（清单为空，请用 git status 自行确认）';
  const head = list.slice(0, 30).map((f) => `- ${f}`).join('\n');
  return list.length > 30 ? `${head}\n- …另有 ${list.length - 30} 个文件，请用 git status 查看` : head;
}

/**
 * 合并冲突交给 Claude 的 prompt（两个已提交分支的内容冲突）。
 *
 * 「不许简单选一边」是这段存在的核心理由：冲突意味着两边**都**对同一片代码做了有意图的修改，
 * `--ours` / `--theirs` 式的整块取舍必然丢掉其中一边的意图，而那正是最难被测试发现的一类缺陷。
 */
export function buildMergeConflictPrompt({ source, target, files, task } = {}) {
  return (
    `请解决一次 git 合并冲突。\n\n` +
    `正在把分支 \`${source}\` 合并进 \`${target}\`，发生内容冲突。\n` +
    (task?.title ? `源分支要解决的问题：${task.title}\n` : '') +
    (task?.detail ? `详细描述：${String(task.detail).slice(0, 500)}\n` : '') +
    `\n冲突文件：\n${fileList(files)}\n\n` +
    `要求：\n` +
    `1. 逐个文件读完上下文再动手，**理解两边各自想做什么**，做语义融合。\n` +
    `2. **不要简单地整块选一边**（不要用 --ours / --theirs 式的取舍）——冲突说明两边都有意图，\n` +
    `   丢掉任何一边都是缺陷，而且是最难被测试发现的那种。确实互斥时，以 \`${source}\` 的\n` +
    `   意图为准，但必须保住 \`${target}\` 上其他改动的正确性。\n` +
    `3. 清掉所有冲突标记（\`<<<<<<<\` / \`=======\` / \`>>>>>>>\`），产出可正常编译运行的代码。\n` +
    `4. **只改冲突文件**，不要顺手重构、格式化或改动其他文件。\n` +
    `5. 改完**不要执行 git add / git commit**，提交由调用方统一完成。\n` +
    `6. 完成后用一段话说明每个文件你是怎么融合的、依据是什么。`
  );
}

/**
 * stash pop 冲突交给 Claude 的 prompt（合并结果 vs 维护者未提交的在写代码）。
 *
 * 与上一个 prompt 的关键差别：**这里的「另一边」是人正在写的活**。它可能语法都不完整，
 * 但绝不能因为「看起来没写完」就丢掉——自动流程覆盖掉人未提交的代码是不可接受的后果，
 * 所以宁可留下不完美的融合，也不许做删减。
 */
export function buildStashMergePrompt({ source, target, files } = {}) {
  return (
    `请融合一次 git stash pop 产生的冲突。\n\n` +
    `背景：自动开发流程刚把分支 \`${source}\` 合并进了 \`${target}\`。合并前，为了不覆盖你面前\n` +
    `这个工作区里**维护者未提交的改动**，那些改动被临时 stash 起来；合并完成后恢复时发生冲突。\n\n` +
    `冲突标记的含义（务必分清）：\n` +
    `- \`<<<<<<< Updated upstream\` 到 \`=======\`：**刚合并进来的代码**（已提交、是团队的成果）\n` +
    `- \`=======\` 到 \`>>>>>>> Stashed changes\`：**维护者本地未提交、正在写的代码**\n\n` +
    `冲突文件：\n${fileList(files)}\n\n` +
    `要求：\n` +
    `1. **两边都要保留**。维护者未提交的改动没有任何备份，丢掉就是永久丢失；\n` +
    `   合并进来的代码是团队成果，同样不能抹掉。\n` +
    `2. 维护者那一侧可能是**半成品**（函数没写完、临时调试代码、语法不完整）——这是正常的，\n` +
    `   **原样保留它，不要替他补全、不要替他删除、不要判断它写得对不对**。\n` +
    `3. 清掉所有冲突标记，让文件回到「合并结果 + 维护者在写的改动」叠加后的样子。\n` +
    `4. **只改冲突文件**，不要碰其他任何文件。\n` +
    `5. 改完**不要执行 git add / git commit / git stash drop**——这些是维护者未提交的改动，\n` +
    `   它们应当停在工作区里，由他自己决定何时提交。\n` +
    `6. 完成后用一段话说明每个文件你是怎么叠加的。`
  );
}
